const assert=require('node:assert/strict');
const {NetworkSim,LEVELS}=require('../src/simulation.js');
const sim=new NetworkSim();
function run(host,command){const r=sim.command(host,command); console.log(`[${host}] ${command} -> ${r.lines.slice(0,2).join(' / ')} | stage:${r.stage}`); return r;}
function patch(a,b){const r=sim.patch(a,b);console.log(`[PATCH] ${a} -> ${b} | stage:${r.stage}`);return r;}
assert.equal(LEVELS.length,5);
assert.equal(sim.stage,0);
assert.equal(sim.status.clientIP,'[disconnected]');
assert.ok(run('client','ipconfig /renew').lines[0].includes('media disconnected'));
assert.equal(sim.stage,0);
assert.ok(patch('gw-console','sw-uplink').lines[0].includes('incompatible'));
assert.equal(sim.stage,0);
patch('gw-lan1','sw-uplink');assert.equal(sim.stage,1);
assert.equal(sim.status.linkOK,true);
assert.equal(sim.status.leaseOK,false);
assert.ok(run('client','ping clinic.ops.example').lines.some(x=>x.includes('no usable')));
run('server','dhcp start');assert.equal(sim.stage,1);
run('client','ipconfig /renew');assert.equal(sim.stage,2);assert.equal(sim.status.leaseOK,true);
assert.equal(sim.status.clientIP,'10.42.1.101');
assert.ok(run('client','ping 10.42.1.20').lines[1].includes('Reply'));
assert.equal(sim.stage,2);
assert.ok(run('client','nslookup clinic.ops.example').lines.some(x=>x.includes('10.42.1.99')));
assert.ok(run('client','ping clinic.ops.example').lines.some(x=>x.includes('Request timed out')));
assert.equal(sim.stage,2);
run('server','dns set clinic.ops.example 10.42.1.20');assert.equal(sim.stage,2);
run('client','ping clinic.ops.example');assert.equal(sim.stage,2,'Ping alone must not prove app health');
run('client','curl https://clinic.ops.example/health');assert.equal(sim.stage,3);assert.equal(sim.status.clinicByName,true);
assert.ok(run('router','audit guest').lines.some(x=>x.includes('EXPOSURE')));
run('router','firewall deny guest clinic');assert.equal(sim.stage,3);assert.equal(sim.status.guestSafe,false);
run('switch','show vlan');run('switch','switch port 6 vlan 30');assert.equal(sim.stage,3);assert.equal(sim.status.guestSafe,true);
run('router','audit guest');assert.equal(sim.stage,4);
assert.ok(run('client','tracert 203.0.113.20').lines.some(x=>x.includes('10.42.0.99')));
assert.equal(sim.stage,4);
run('router','route set default 10.42.0.254');assert.equal(sim.stage,4);
run('client','tracert 203.0.113.20');assert.equal(sim.stage,4,'Traceroute alone must not prove app health');
run('client','curl https://backup.example.net/health');assert.equal(sim.stage,5);assert.equal(sim.done,true);
assert.equal(sim.s.score,2500);
const restored=new NetworkSim(sim.serialize());assert.equal(restored.stage,5);
restored.command('server','dhcp stop');
assert.equal(restored.status.leaseOK,true,'Existing DHCP lease should persist while service is stopped');
assert.equal(restored.status.clientIP,'10.42.1.101');
const r=restored.command('switch','switch port 6 vlan 10');
assert.equal(restored.status.guestSafe,false,'Changing guest VLAN should immediately affect live security state');
assert.equal(restored.s.verifiedGuests,false);
assert.equal(restored.stage,5,'Completed missions remain recorded after an experiment');
const weird=new NetworkSim();const invalid=weird.command('server','dns set clinic.ops.example 10.42.1.999');
assert.equal(weird.s.dnsA,'10.42.1.99','invalid address not committed');
console.log('PASS: 5 mission progression, negative diagnostics, VLAN isolation and save/restore');
